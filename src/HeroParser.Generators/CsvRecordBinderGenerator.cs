                break;

            case "double":
            case "System.Double":
                EmitCharNumericParsing(builder, member, "TryParseDouble");
                break;

            case "float":
            case "System.Single":
                EmitCharNumericParsing(builder, member, "TryParseSingle");
                break;

            case "bool":
            case "System.Boolean":
                EmitCharBooleanParsing(builder, member);
                break;

            case "System.DateTime":
                EmitCharDateTimeParsing(builder, member, "TryParseDateTime");
                break;

            case "System.DateTimeOffset":
                EmitCharDateTimeParsing(builder, member, "TryParseDateTimeOffset");
                break;

            case "System.DateOnly":
                EmitCharDateTimeParsing(builder, member, "TryParseDateOnly");
                break;

            case "System.TimeOnly":
                EmitCharDateTimeParsing(builder, member, "TryParseTimeOnly");
                break;

            case "System.Guid":
                EmitCharGuidParsing(builder, member);
                break;

            case "char":
            case "System.Char":
                EmitTryParseScalar(builder, member, "TryParseChar", isByte: false);
                break;

            case "System.TimeSpan":
                EmitDateTimeParsingWithFormat(builder, member, "TryParseTimeSpan", isByte: false);
