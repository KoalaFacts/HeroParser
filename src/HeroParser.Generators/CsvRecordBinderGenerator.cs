    private static void EmitCharInlinePropertyBinding(SourceBuilder builder, MemberDescriptor member)
    {
        var indexField = $"_{member.MemberName}Index";
        var isRequired = !member.IsNullable && member.BaseTypeName != "string";

        builder.AppendLine($"if ((uint){indexField} < (uint)columnCount)");
        builder.AppendLine("{");
        builder.Indent();
        if (member.BaseTypeName == "string")
        {
            builder.AppendLine($"var text = row.GetValueString({indexField});");
            builder.AppendLine("var span = text.AsSpan();");
        }
        else
        {
            builder.AppendLine($"var column = row.GetValue({indexField});");
            builder.AppendLine("var span = column.Span;");
        }
        builder.AppendLine("bool isNullVal = _nullValuesChar is not null && IsNullValue(span, _nullValuesChar);");

        if (member.Validation.NotNull || member.Validation.NotEmpty)
        {
            builder.AppendLine("if (isNullVal || IsAllAsciiWhiteSpace(span))");
            builder.AppendLine("{");
            builder.Indent();
