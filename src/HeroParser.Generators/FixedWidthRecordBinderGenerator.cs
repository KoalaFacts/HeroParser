    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // Use ForAttributeWithMetadataName for better caching
        var provider = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                generateAttributeNames[0],
                predicate: static (node, _) => node is ClassDeclarationSyntax or RecordDeclarationSyntax or StructDeclarationSyntax,
                transform: static (ctx, ct) => TransformToDescriptor(ctx, ct))
            .Where(static x => x is not null);

        // Generate per-type descriptor files for better incrementality
        context.RegisterSourceOutput(provider, static (spc, descriptor) => EmitDescriptor(spc, descriptor!));

        // Generate registration file
        context.RegisterSourceOutput(provider.Collect(), static (spc, descriptors) =>
        {
            var all = descriptors.Where(x => x is not null).ToList();
            if (all.Count > 0)
                EmitRegistration(spc, all!);
        });
    }

    private static TypeDescriptor? TransformToDescriptor(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol symbol)
            return null;

        var target = new RecordTypeTarget(symbol);
        if (symbol.IsAbstract || !target.IsAccessible)
            return null;

        return BuildDescriptor(target, ct);
    }

    private static void EmitDescriptor(SourceProductionContext context, TypeDescriptor descriptor)
    {
        // Report diagnostics
        foreach (var diag in descriptor.Diagnostics)
        {
            context.ReportDiagnostic(diag);
        }

        var binderMembers = GetMembersWithSetters(descriptor.Members);
        if (binderMembers.Count > 0)
        {
            var builder = new SourceBuilder(16384);
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("#nullable enable");
            builder.AppendLine("using System;");
            builder.AppendLine("using System.Collections.Generic;");
            builder.AppendLine("using System.Globalization;");
            builder.AppendLine("using System.Runtime.CompilerServices;");
            builder.AppendLine("using System.Text;");
            builder.AppendLine("using HeroParser.Validation;");
            builder.AppendLine();
            builder.AppendLine($"namespace {GENERATED_NAMESPACE};");
            builder.AppendLine();

            // Emit descriptor class for optimized binding (writer + descriptor registration)
            EmitDescriptorClass(builder, descriptor.FullyQualifiedName, descriptor.SafeClassName, binderMembers);

            // Emit generated binder class for inline validation support
            EmitGeneratedBinderClass(builder, descriptor.FullyQualifiedName, descriptor.SafeClassName, binderMembers);
            EmitGeneratedByteBinderClass(builder, descriptor.FullyQualifiedName, descriptor.SafeClassName, binderMembers);

            context.AddSource($"FixedWidthDescriptor.{descriptor.SafeClassName}.g.cs", builder.ToString());
        }

        var writerMembers = GetMembersWithGetters(descriptor.Members);
        if (writerMembers.Count > 0)
        {
            var writerBuilder = new SourceBuilder(16384);
            writerBuilder.AppendLine("// <auto-generated/>");
            writerBuilder.AppendLine("#nullable enable");
            writerBuilder.AppendLine("#pragma warning disable CS8602");
            writerBuilder.AppendLine("#pragma warning disable CS8625");
            writerBuilder.AppendLine("using System;");
            writerBuilder.AppendLine("using System.Collections.Generic;");
            writerBuilder.AppendLine("using System.Globalization;");
            writerBuilder.AppendLine("using System.Runtime.CompilerServices;");
            writerBuilder.AppendLine("using System.Text;");
            writerBuilder.AppendLine("using HeroParser.Validation;");
            writerBuilder.AppendLine();
            writerBuilder.AppendLine($"namespace {GENERATED_NAMESPACE};");
            writerBuilder.AppendLine();

            EmitInlineSourceWriterClass(writerBuilder, descriptor.FullyQualifiedName, descriptor.SafeClassName, writerMembers, descriptor.IsValueType);

            context.AddSource($"FixedWidthInlineSourceWriter.{descriptor.SafeClassName}.g.cs", writerBuilder.ToString());
        }
    }

    private static void EmitDescriptorClass(SourceBuilder builder, string fullyQualifiedName, string safeClassName, IReadOnlyList<MemberDescriptor> members)
    {
        var descriptorClassName = $"FixedWidthDescriptor_{safeClassName}";

        builder.AppendLine($"internal static class {descriptorClassName}");
        builder.AppendLine("{");
        builder.Indent();

        // Emit static setter methods for each property
        foreach (var member in members)
        {
            EmitPropertySetterMethod(builder, fullyQualifiedName, member);
        }
        builder.AppendLine();

        // Emit static descriptor instance using Lazy<T> for thread-safe initialization
        builder.AppendLine($"private static readonly global::System.Lazy<{DESCRIPTOR_TYPE}<{fullyQualifiedName}>> _instance = new(CreateDescriptor);");
        builder.AppendLine();

        // Emit GetDescriptor method that returns the cached descriptor
        builder.AppendLine($"public static {DESCRIPTOR_TYPE}<{fullyQualifiedName}> GetDescriptor() => _instance.Value;");
        builder.AppendLine();

        // Emit CreateDescriptor method that builds the descriptor
        builder.AppendLine($"private static {DESCRIPTOR_TYPE}<{fullyQualifiedName}> CreateDescriptor()");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"var properties = new {PROPERTY_DESCRIPTOR_TYPE}<{fullyQualifiedName}>[]");
        builder.AppendLine("{");
        builder.Indent();

        foreach (var member in members)
        {
            var isRequired = !member.IsNullable && !member.IsReferenceType;
            builder.AppendLine($"new {PROPERTY_DESCRIPTOR_TYPE}<{fullyQualifiedName}>(" +
                $"\"{member.MemberName}\", " +
                $"{member.Start}, " +
                $"{member.Length}, " +
                $"{new CSharpCharLiteral(member.PadChar).Quoted}, " +
                $"{FIELD_ALIGNMENT_TYPE}.{member.Alignment}, " +
                $"Set_{member.MemberName}, " +
                $"{(isRequired ? "true" : "false")}),");
        }

        builder.Unindent();
        builder.AppendLine("};");
        builder.AppendLine($"return new {DESCRIPTOR_TYPE}<{fullyQualifiedName}>(properties);");
        builder.Unindent();
        builder.AppendLine("}");

        EmitCharParsingHelpers(builder, members);

        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitPropertySetterMethod(SourceBuilder builder, string fullyQualifiedName, MemberDescriptor member)
    {
        builder.AppendLine($"private static void Set_{member.MemberName}(ref {fullyQualifiedName} instance, ReadOnlySpan<char> span, CultureInfo culture)");
        builder.AppendLine("{");
        builder.Indent();

        // Emit parsing logic based on type
        EmitSetterParsingLogic(builder, member);

        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitGeneratedBinderClass(SourceBuilder builder, string fullyQualifiedName, string safeClassName, IReadOnlyList<MemberDescriptor> members)
    {
        var binderClassName = $"FixedWidthInlineCharSourceBinder_{safeClassName}";

        builder.AppendLine($"internal sealed class {binderClassName} : {BINDER_INTERFACE_TYPE}<{fullyQualifiedName}>");
        builder.AppendLine("{");
        builder.Indent();

        // Emit static Regex fields for Pattern validation
        foreach (var member in members)
        {
            if (member.Validation.Pattern != null)
            {
                var escapedPattern = new CSharpStringLiteral(member.Validation.Pattern).Escaped;
                builder.AppendLine($"private static readonly global::System.Text.RegularExpressions.Regex _pattern_{member.MemberName} = new(\"{escapedPattern}\", global::System.Text.RegularExpressions.RegexOptions.None, TimeSpan.FromMilliseconds({member.Validation.PatternTimeoutMs}));");
            }
        }

        // Fields
        builder.AppendLine("private readonly CultureInfo _culture;");
        builder.AppendLine("private readonly HashSet<string>? _nullValues;");
        builder.AppendLine();

        // Constructor
        builder.AppendLine($"public {binderClassName}(CultureInfo? culture, IReadOnlyList<string>? nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("_culture = culture ?? CultureInfo.InvariantCulture;");
        builder.AppendLine("_nullValues = nullValues is { Count: > 0 }");
        builder.AppendLine("    ? new HashSet<string>(nullValues, StringComparer.Ordinal)");
        builder.AppendLine("    : null;");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        // TryBind method
        builder.AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        builder.AppendLine($"public bool TryBind(global::HeroParser.FixedWidths.FixedWidthCharSpanRow row, out {fullyQualifiedName} result, List<ValidationError>? errors = null)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"result = new {fullyQualifiedName}();");
        builder.AppendLine("return BindInto(ref result, row, errors);");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        // BindInto method with inline parsing + validation
        EmitGeneratedBindIntoMethod(builder, fullyQualifiedName, members);

        // Factory method
        builder.AppendLine($"public static {BINDER_INTERFACE_TYPE}<{fullyQualifiedName}> Create(CultureInfo? culture, IReadOnlyList<string>? nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"return new {binderClassName}(culture, nullValues);");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        // IsNullValue helper
        builder.AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        builder.AppendLine("private static bool IsNullValue(ReadOnlySpan<char> value, HashSet<string> nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("return nullValues.Contains(new string(value));");
        builder.Unindent();
        builder.AppendLine("}");

        EmitCharParsingHelpers(builder, members);

        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitGeneratedBindIntoMethod(SourceBuilder builder, string fullyQualifiedName, IReadOnlyList<MemberDescriptor> members)
    {
        bool anyValidation = HasAnyValidation(members);

        builder.AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        builder.AppendLine($"public bool BindInto(ref {fullyQualifiedName} instance, global::HeroParser.FixedWidths.FixedWidthCharSpanRow row, List<ValidationError>? errors = null)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("var cultureLocal = _culture;");
        builder.AppendLine("var nullVals = _nullValues;");
        builder.AppendLine("var rowNumber = row.RecordNumber;");

        if (anyValidation)
        {
            builder.AppendLine("bool valid = true;");
        }

        builder.AppendLine();

        foreach (var member in members)
        {
            EmitGeneratedPropertyBinding(builder, member);
        }

        builder.AppendLine(anyValidation ? "return valid;" : "return true;");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitGeneratedByteBinderClass(SourceBuilder builder, string fullyQualifiedName, string safeClassName, IReadOnlyList<MemberDescriptor> members)
    {
        var binderClassName = $"FixedWidthInlineByteSourceBinder_{safeClassName}";

        builder.AppendLine($"internal sealed class {binderClassName} : {BYTE_BINDER_INTERFACE_TYPE}<{fullyQualifiedName}>");
        builder.AppendLine("{");
        builder.Indent();

        foreach (var member in members)
        {
            if (member.Validation.Pattern != null)
            {
                var escapedPattern = new CSharpStringLiteral(member.Validation.Pattern).Escaped;
                builder.AppendLine($"private static readonly global::System.Text.RegularExpressions.Regex _byte_pattern_{member.MemberName} = new(\"{escapedPattern}\", global::System.Text.RegularExpressions.RegexOptions.None, TimeSpan.FromMilliseconds({member.Validation.PatternTimeoutMs}));");
            }
        }

        builder.AppendLine("private readonly CultureInfo _culture;");
        builder.AppendLine("private readonly byte[][]? _nullValues;");
        builder.AppendLine();

        builder.AppendLine($"public {binderClassName}(CultureInfo? culture, IReadOnlyList<string>? nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("_culture = culture ?? CultureInfo.InvariantCulture;");
        builder.AppendLine("_nullValues = nullValues is { Count: > 0 }");
        builder.AppendLine("    ? CreateNullValuesUtf8(nullValues)");
        builder.AppendLine("    : null;");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        builder.AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        builder.AppendLine($"public bool TryBind(global::HeroParser.FixedWidths.FixedWidthByteSpanRow row, out {fullyQualifiedName} result, List<ValidationError>? errors = null)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"result = new {fullyQualifiedName}();");
        builder.AppendLine("return BindInto(ref result, row, errors);");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        EmitGeneratedByteBindIntoMethod(builder, fullyQualifiedName, members);

        builder.AppendLine($"public static {BYTE_BINDER_INTERFACE_TYPE}<{fullyQualifiedName}> Create(CultureInfo? culture, IReadOnlyList<string>? nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"return new {binderClassName}(culture, nullValues);");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        builder.AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        builder.AppendLine("private static bool IsNullValue(ReadOnlySpan<byte> value, byte[][] nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("foreach (var nullValue in nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("if (value.SequenceEqual(nullValue))");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("return true;");
        builder.Unindent();
        builder.AppendLine("}");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine("return false;");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();

        builder.AppendLine("private static byte[][] CreateNullValuesUtf8(IReadOnlyList<string> nullValues)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("var encoded = new byte[nullValues.Count][];");
        builder.AppendLine("for (int i = 0; i < nullValues.Count; i++)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("encoded[i] = System.Text.Encoding.UTF8.GetBytes(nullValues[i]);");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine("return encoded;");
        builder.Unindent();
        builder.AppendLine("}");

        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitGeneratedByteBindIntoMethod(SourceBuilder builder, string fullyQualifiedName, IReadOnlyList<MemberDescriptor> members)
    {
        bool anyValidation = HasAnyValidation(members);

        builder.AppendLine("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        builder.AppendLine($"public bool BindInto(ref {fullyQualifiedName} instance, global::HeroParser.FixedWidths.FixedWidthByteSpanRow row, List<ValidationError>? errors = null)");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("var cultureLocal = _culture;");
        builder.AppendLine("var nullVals = _nullValues;");
        builder.AppendLine("var rowNumber = row.RecordNumber;");

        if (anyValidation)
        {
            builder.AppendLine("bool valid = true;");
        }

        builder.AppendLine();

        foreach (var member in members)
        {
            EmitGeneratedBytePropertyBinding(builder, member);
        }

        builder.AppendLine(anyValidation ? "return valid;" : "return true;");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitGeneratedBytePropertyBinding(SourceBuilder builder, MemberDescriptor member)
    {
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"var field = row.GetField({member.Start}, {member.Length}, (byte){new CSharpCharLiteral(member.PadChar).Quoted}, {FIELD_ALIGNMENT_TYPE}.{member.Alignment});");
        builder.AppendLine("var utf8 = field.ByteSpan;");
        builder.AppendLine();
        builder.AppendLine("bool isNullVal = nullVals is not null && IsNullValue(utf8, nullVals);");

        if (member.Validation.NotNull || member.Validation.NotEmpty)
        {
            builder.AppendLine("if (isNullVal || utf8.IsEmpty || FixedWidthUtf8BindingHelper.IsNullOrWhiteSpace(utf8))");
            builder.AppendLine("{");
            builder.Indent();
            if (member.Validation.NotNull)
            {
                EmitByteAddValidationError(builder, member, "NotNull", "Value is required");
            }
            else
            {
                EmitByteAddValidationError(builder, member, "NotEmpty", "Value must not be empty or whitespace");
            }
            builder.AppendLine("valid = false;");
            builder.Unindent();
            builder.AppendLine("}");
        }

        builder.AppendLine("if (!isNullVal)");
        builder.AppendLine("{");
        builder.Indent();

        EmitByteInlineParsingLogic(builder, member);

        if (HasAnyValidation(member, excludeNotNull: true))
        {
            EmitByteValidationChecks(builder, member, excludeNotNull: true);
        }

        builder.Unindent();
        builder.AppendLine("}");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitGeneratedPropertyBinding(SourceBuilder builder, MemberDescriptor member)
    {
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine($"var field = row.GetField({member.Start}, {member.Length}, {new CSharpCharLiteral(member.PadChar).Quoted}, {FIELD_ALIGNMENT_TYPE}.{member.Alignment});");
        builder.AppendLine("var span = field.CharSpan;");
        builder.AppendLine();
        builder.AppendLine("bool isNullVal = nullVals is not null && IsNullValue(span, nullVals);");

        if (member.Validation.NotNull || member.Validation.NotEmpty)
        {
            builder.AppendLine("if (isNullVal || span.IsEmpty || span.IsWhiteSpace())");
            builder.AppendLine("{");
            builder.Indent();
            if (member.Validation.NotNull)
            {
                EmitAddValidationError(builder, member, "NotNull", "Value is required");
            }
            else
            {
                EmitAddValidationError(builder, member, "NotEmpty", "Value must not be empty or whitespace");
            }
            builder.AppendLine("valid = false;");
            builder.Unindent();
            builder.AppendLine("}");
        }

        builder.AppendLine("if (!isNullVal)");
        builder.AppendLine("{");
        builder.Indent();

        // Emit inline parsing (same logic as setter methods but inline)
        EmitInlineParsingLogic(builder, member);

        // Emit validation checks after parsing
        if (HasAnyValidation(member, excludeNotNull: true))
        {
            EmitValidationChecks(builder, member, excludeNotNull: true);
        }

        builder.Unindent();
        builder.AppendLine("}");
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitByteInlineParsingLogic(SourceBuilder builder, MemberDescriptor member)
    {
        var baseType = member.BaseTypeName;

#pragma warning disable IDE0010 // Populate switch - intentionally not exhaustive
        switch (baseType)
        {
            case "string":
                builder.AppendLine($"instance.{member.MemberName} = FixedWidthUtf8BindingHelper.Decode(utf8);");
                break;

            case "int":
            case "System.Int32":
                EmitByteNumericParsing(builder, member, "TryParseInt32", "int");
                break;

            case "long":
            case "System.Int64":
                EmitByteNumericParsing(builder, member, "TryParseInt64", "long");
                break;

            case "short":
            case "System.Int16":
                EmitByteNumericParsing(builder, member, "TryParseInt16", "short");
                break;

            case "byte":
            case "System.Byte":
                EmitByteNumericParsing(builder, member, "TryParseByte", "byte");
                break;

            case "uint":
            case "System.UInt32":
                EmitByteNumericParsing(builder, member, "TryParseUInt32", "uint");
                break;

            case "ulong":
            case "System.UInt64":
                EmitByteNumericParsing(builder, member, "TryParseUInt64", "ulong");
                break;

            case "ushort":
            case "System.UInt16":
                EmitByteNumericParsing(builder, member, "TryParseUInt16", "ushort");
                break;

            case "sbyte":
            case "System.SByte":
                EmitByteNumericParsing(builder, member, "TryParseSByte", "sbyte");
                break;

            case "decimal":
            case "System.Decimal":
                EmitByteNumericParsing(builder, member, "TryParseDecimal", "decimal");
                break;

            case "double":
            case "System.Double":
                EmitByteNumericParsing(builder, member, "TryParseDouble", "double");
                break;

            case "float":
            case "System.Single":
                EmitByteNumericParsing(builder, member, "TryParseSingle", "float");
                break;

            case "System.Half":
                EmitByteNumericParsing(builder, member, "TryParseHalf", "Half");
                break;

            case "System.Int128":
                EmitByteNumericParsing(builder, member, "TryParseInt128", "Int128");
                break;

            case "System.UInt128":
                EmitByteNumericParsing(builder, member, "TryParseUInt128", "UInt128");
                break;

            case "System.Numerics.BigInteger":
                EmitByteNumericParsing(builder, member, "TryParseBigInteger", "BigInteger");
                break;

            case "bool":
            case "System.Boolean":
                EmitByteBooleanParsing(builder, member);
                break;

            case "char":
            case "System.Char":
                EmitByteSimpleParsing(builder, member, "TryParseChar", "char", nullableAssignsDefault: false);
                break;

            case "System.DateTime":
                EmitByteDateTimeParsing(builder, member, "DateTime");
                break;

            case "System.DateTimeOffset":
                EmitByteDateTimeParsing(builder, member, "DateTimeOffset");
                break;

            case "System.DateOnly":
                EmitByteDateTimeParsing(builder, member, "DateOnly");
                break;

            case "System.TimeOnly":
                EmitByteDateTimeParsing(builder, member, "TimeOnly");
                break;

            case "System.TimeSpan":
                EmitByteDateTimeParsing(builder, member, "TimeSpan");
                break;

            case "System.Guid":
                EmitByteSimpleParsing(builder, member, "TryParseGuid", "Guid", nullableAssignsDefault: false);
                break;

            case "System.Uri":
                EmitByteSimpleParsing(builder, member, "TryParseUri", "Uri", nullableAssignsDefault: true);
                break;

            case "byte[]":
            case "System.Byte[]":
                EmitByteSimpleParsing(builder, member, "TryParseBase64Bytes", "byte[]", nullableAssignsDefault: true);
                break;

            default:
                if (member.IsEnum)
                {
                    EmitByteEnumParsing(builder, member);
                }
                else if (member.IsUtf8SpanParsable)
                {
                    EmitByteSpanParsableParsing(builder, member, "TryParseUtf8Isomorphic");
                }
                else if (member.IsSpanParsable)
                {
                    EmitByteSpanParsableParsing(builder, member, "TryParseIsomorphic");
                }
                else
                {
                    builder.AppendLine($"instance.{member.MemberName} = FixedWidthUtf8BindingHelper.Decode(utf8);");
                }
                break;
        }
#pragma warning restore IDE0010
    }

    private static void EmitByteNumericParsing(SourceBuilder builder, MemberDescriptor member, string helperMethod, string typeName)
    {
        var propertyName = member.MemberName;

        if (member.IsNullable)
        {
            builder.AppendLine("if (utf8.IsEmpty || FixedWidthUtf8BindingHelper.IsNullOrWhiteSpace(utf8)) { /* null */ }");
            builder.AppendLine($"else if (FixedWidthUtf8BindingHelper.{helperMethod}(utf8, cultureLocal, out var parsed_{propertyName}))");
            builder.AppendLine($"    instance.{propertyName} = parsed_{propertyName};");
            builder.AppendLine("else");
            EmitByteThrowParseError(builder, propertyName, typeName);
        }
        else
        {
            builder.AppendLine($"if (FixedWidthUtf8BindingHelper.{helperMethod}(utf8, cultureLocal, out var parsed_{propertyName}))");
            builder.AppendLine($"    instance.{propertyName} = parsed_{propertyName};");
            if (member.Validation.NotNull)
                builder.AppendLine("else if (!FixedWidthUtf8BindingHelper.IsNullOrWhiteSpace(utf8))");
            else
                builder.AppendLine("else");
            EmitByteThrowParseError(builder, propertyName, typeName);
        }
    }

    private static void EmitByteBooleanParsing(SourceBuilder builder, MemberDescriptor member)
    {
        var propertyName = member.MemberName;

        if (member.IsNullable)
        {
            builder.AppendLine("if (utf8.IsEmpty || FixedWidthUtf8BindingHelper.IsNullOrWhiteSpace(utf8)) { /* null */ }");
            builder.AppendLine($"else if (FixedWidthUtf8BindingHelper.TryParseBoolean(utf8, out var parsed_{propertyName}))");
            builder.AppendLine($"    instance.{propertyName} = parsed_{propertyName};");
            builder.AppendLine("else");
            EmitByteThrowParseError(builder, propertyName, "bool");
