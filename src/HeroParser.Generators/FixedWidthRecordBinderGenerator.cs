    private static void EmitInlineSourceWriterClass(SourceBuilder builder, string fullyQualifiedName, string safeClassName, IReadOnlyList<MemberDescriptor> members, bool isValueType)
    {
        var writerClassName = $"FixedWidthInlineSourceWriter_{safeClassName}";
        builder.AppendLine($"internal sealed class {writerClassName} : global::HeroParser.FixedWidths.Writing.IFixedWidthSourceWriter<{fullyQualifiedName}>");
        builder.AppendLine("{");
        builder.Indent();

        // WriteRecord
        builder.AppendLine($"public void WriteRecord(global::HeroParser.FixedWidths.Writing.FixedWidthStreamWriter writer, {fullyQualifiedName} record, global::HeroParser.FixedWidths.Writing.FixedWidthWriteOptions options)");
        builder.AppendLine("{");
        builder.Indent();
        if (!isValueType)
        {
            builder.AppendLine("if (record is null) return;");
            builder.AppendLine();
        }

        // Loop over members (already sorted by Start position)
        int currentPos = 0;
        foreach (var member in members)
        {
            // Gap check
            if (member.Start > currentPos)
            {
                int gapSize = member.Start - currentPos;
                builder.AppendLine($"writer.WriteField(global::System.ReadOnlySpan<char>.Empty, {gapSize}, global::HeroParser.FieldAlignment.Left, options.DefaultPadChar);");
            }

            // Emit field writing
            EmitFixedWidthWriteField(builder, member);

            currentPos = member.Start + member.Length;
        }

        // Trailing gap check
        int recordLength = members.Count > 0 ? members.Max(m => m.Start + m.Length) : 0;
        if (recordLength > currentPos)
        {
            int trailingGap = recordLength - currentPos;
            builder.AppendLine($"writer.WriteField(global::System.ReadOnlySpan<char>.Empty, {trailingGap}, global::HeroParser.FieldAlignment.Left, options.DefaultPadChar);");
        }

        builder.Unindent();
        builder.AppendLine("}");

        EmitWriterHelpers(builder, members);

        builder.Unindent();
        builder.AppendLine("}");
    }

    private static void EmitWriterHelpers(SourceBuilder builder, IReadOnlyList<MemberDescriptor> members)
    {
