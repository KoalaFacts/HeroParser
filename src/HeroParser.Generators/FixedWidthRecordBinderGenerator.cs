        builder.AppendLine("{");
        builder.Indent();

        foreach (var descriptor in descriptors)
        {
            var binderMembers = GetMembersWithSetters(descriptor.Members);
            if (binderMembers.Count > 0)
            {
                EmitDescriptorRegistration(builder, descriptor.FullyQualifiedName, descriptor.SafeClassName);
                EmitGeneratedBinderRegistration(builder, descriptor.FullyQualifiedName, descriptor.SafeClassName);
                EmitGeneratedByteBinderRegistration(builder, descriptor.FullyQualifiedName, descriptor.SafeClassName);
            }

            var writerMembers = GetMembersWithGetters(descriptor.Members);
            if (writerMembers.Count > 0)
            {
                EmitWriterRegistration(builder, descriptor.FullyQualifiedName, writerMembers);
                var directWriterClassName = $"global::{GENERATED_NAMESPACE}.FixedWidthInlineSourceWriter_{descriptor.SafeClassName}";
                builder.AppendLine($"{WRITER_FACTORY_TYPE}.RegisterDirectWriter<{descriptor.FullyQualifiedName}>(new {directWriterClassName}());");
            }
        }

        builder.Unindent();
        builder.AppendLine("}");
        builder.Unindent();
        builder.AppendLine("}");

        context.AddSource("FixedWidthRecordBinderFactory.Registration.g.cs", builder.ToString());
    }

