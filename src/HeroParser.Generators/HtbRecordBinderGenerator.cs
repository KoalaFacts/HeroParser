    private static void EmitRegistration(SourceProductionContext context, IReadOnlyList<TypeDescriptor> descriptors)
    {
        var builder = new SourceBuilder(8192);
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Runtime.CompilerServices;");
        builder.AppendLine();
        builder.AppendLine($"namespace {GENERATED_NAMESPACE};");
        builder.AppendLine();
        builder.AppendLine("file static class HtbRecordBinderGeneratedRegistration");
        builder.AppendLine("{");
        builder.Indent();
        builder.AppendLine("[ModuleInitializer]");
        builder.AppendLine("internal static void Register()");
        builder.AppendLine("{");
        builder.Indent();

        foreach (var descriptor in descriptors)
        {
            var readMembers = new List<MemberDescriptor>();
            var writeMembers = new List<MemberDescriptor>();
            foreach (var m in descriptor.Members)
            {
                if (m.HasSetter)
                    readMembers.Add(m);
                if (m.HasGetter)
                    writeMembers.Add(m);
            }

            if (readMembers.Count == 0 && writeMembers.Count == 0)
                continue;

            var binderClassName = $"global::{GENERATED_NAMESPACE}.HtbInlineBinder_{descriptor.SafeClassName}";
            if (readMembers.Count > 0)
                builder.AppendLine($"{BINDER_FACTORY_TYPE}.RegisterBinder<{descriptor.FullyQualifiedName}>(schema => new {binderClassName}(schema));");

            if (writeMembers.Count > 0)
            {
                builder.AppendLine($"{WRITER_FACTORY_TYPE}.RegisterWriter<{descriptor.FullyQualifiedName}>(() => new {binderClassName}());");

                builder.AppendLine($"global::HeroParser.Htbs.Records.HtbSchema.RegisterSchemaProvider<{descriptor.FullyQualifiedName}>(() => new global::HeroParser.Htbs.Records.HtbSchema(");
                builder.AppendLine("    new global::HeroParser.Htbs.Records.HtbColumn[]");
                builder.AppendLine("    {");
                for (int i = 0; i < writeMembers.Count; i++)
                {
                    var member = writeMembers[i];
                    var isNullable = member.IsNullable || member.IsReferenceType;
                    var isNullableStr = isNullable ? "true" : "false";
                    var typeNameStr = GetHtbDataTypeName(member.BaseTypeName);
                    var comma = i == writeMembers.Count - 1 ? "" : ",";
                    var escapedHeader = new CSharpStringLiteral(member.HeaderName).Escaped;
                    builder.AppendLine($"        new global::HeroParser.Htbs.Records.HtbColumn(\"{escapedHeader}\", global::HeroParser.Htbs.Records.HtbDataType.{typeNameStr}, {isNullableStr}){comma}");
                }
                builder.AppendLine("    }");
                builder.AppendLine("));");
            }
        }

        builder.Unindent();
        builder.AppendLine("}");
        builder.Unindent();
        builder.AppendLine("}");

        context.AddSource("HtbRecordBinderFactory.Registration.g.cs", builder.ToString());
    }

    private static string GetHtbDataTypeName(string baseTypeName)
    {
        return baseTypeName switch
        {
            "int" or "System.Int32" => "Int32",
            "long" or "System.Int64" => "Int64",
            "float" or "System.Single" => "Float",
            "double" or "System.Double" => "Double",
            "decimal" or "System.Decimal" => "Decimal",
            "bool" or "System.Boolean" => "Boolean",
            "System.DateTime" => "DateTime",
            "string" or "System.String" => "String",
            "System.Guid" => "Guid",
            "float[]" or "System.Single[]" => "FloatArray",
            "System.DateTimeOffset" => "DateTimeOffset",
            "System.DateOnly" => "DateOnly",
            "System.TimeOnly" => "TimeOnly",
            "System.TimeSpan" => "TimeSpan",
            "short" or "System.Int16" => "Int16",
            "ushort" or "System.UInt16" => "UInt16",
            "byte" or "System.Byte" => "Byte",
            "sbyte" or "System.SByte" => "SByte",
            "uint" or "System.UInt32" => "UInt32",
            "ulong" or "System.UInt64" => "UInt64",
            "char" or "System.Char" => "Char",
            "System.Half" => "Half",
            "System.Int128" => "Int128",
            "System.UInt128" => "UInt128",
            "byte[]" or "System.Byte[]" => "ByteArray",
            "System.Numerics.BigInteger" => "BigInteger",
            "System.Uri" => "Uri",
            _ => "Unknown"
        };
    }

    private static TypeDescriptor? BuildDescriptor(RecordTypeTarget target, CancellationToken ct)
    {
        var type = target.Symbol;
        var members = new List<MemberDescriptor>();
        var diagnostics = new List<Diagnostic>();

        foreach (var property in type.GetMembers().OfType<IPropertySymbol>())
        {
            ct.ThrowIfCancellationRequested();

            if (property.IsStatic || property.IsIndexer)
                continue;

            var hasSetter = property.SetMethod is { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false };
            var hasGetter = property.GetMethod is { DeclaredAccessibility: Accessibility.Public };

            if (!hasSetter && !hasGetter)
                continue;

            // [TabularMap]
            var mapAttribute = new SymbolAttributes(property).FindFirst(columnAttributeNames);
            string headerName = property.Name;
            int? attributeIndex = null;
            if (mapAttribute is not null)
            {
                foreach (var arg in mapAttribute.NamedArguments)
                {
                    if (arg.Key == "Name" && arg.Value.Value is string s && !string.IsNullOrWhiteSpace(s))
                    {
                        headerName = s;
                    }
                    else if (arg.Key == "Index" && arg.Value.Value is int i && i >= 0)
                    {
                        attributeIndex = i;
                    }
                }
            }

            var typeMeta = new TypeMetadata(property.Type);
            var baseTypeName = typeMeta.BaseTypeName;
            bool isNullable = typeMeta.IsNullableValueType;
            bool isReferenceType = typeMeta.IsReferenceType;

#pragma warning disable IDE0010
            HtbDataType dataType = baseTypeName switch
            {
                "int" or "System.Int32" => HtbDataType.Int32,
                "long" or "System.Int64" => HtbDataType.Int64,
                "float" or "System.Single" => HtbDataType.Float,
                "double" or "System.Double" => HtbDataType.Double,
                "decimal" or "System.Decimal" => HtbDataType.Decimal,
                "bool" or "System.Boolean" => HtbDataType.Boolean,
                "System.DateTime" => HtbDataType.DateTime,
                "string" or "System.String" => HtbDataType.String,
                "System.Guid" => HtbDataType.Guid,
                "float[]" or "System.Single[]" => HtbDataType.FloatArray,
                "System.DateTimeOffset" => HtbDataType.DateTimeOffset,
                "System.DateOnly" => HtbDataType.DateOnly,
                "System.TimeOnly" => HtbDataType.TimeOnly,
                "System.TimeSpan" => HtbDataType.TimeSpan,
                "short" or "System.Int16" => HtbDataType.Int16,
                "ushort" or "System.UInt16" => HtbDataType.UInt16,
                "byte" or "System.Byte" => HtbDataType.Byte,
                "sbyte" or "System.SByte" => HtbDataType.SByte,
                "uint" or "System.UInt32" => HtbDataType.UInt32,
                "ulong" or "System.UInt64" => HtbDataType.UInt64,
                "char" or "System.Char" => HtbDataType.Char,
                "System.Half" => HtbDataType.Half,
                "System.Int128" => HtbDataType.Int128,
                "System.UInt128" => HtbDataType.UInt128,
                "byte[]" or "System.Byte[]" => HtbDataType.ByteArray,
                "System.Numerics.BigInteger" => HtbDataType.BigInteger,
                "System.Uri" => HtbDataType.Uri,
                _ => HtbDataType.Unknown
            };
#pragma warning restore IDE0010

            if (dataType == HtbDataType.Unknown)
            {
                // Skip unsupported properties
                continue;
            }

            var typeName = typeMeta.FullyQualifiedName;
            var typeofTypeName = property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var validation = ParsedValidationRules.ExtractWithoutDiagnostics(property);

            members.Add(new MemberDescriptor(
                property.Name,
                headerName,
                attributeIndex,
                typeName,
                typeofTypeName,
                baseTypeName,
                isNullable,
                isReferenceType,
                hasSetter,
                hasGetter,
                validation));
        }

        if (members.Count == 0 && diagnostics.Count == 0)
            return null;

        // Sort members in the exact same sorted order as HtbSchema.FromType<T>() (explicit Index ascending first, then alphabetical fallback)
        var sortedMembers = members
            .OrderBy(m => m.AttributeIndex.HasValue && m.AttributeIndex.Value >= 0 ? m.AttributeIndex.Value : int.MaxValue)
            .ThenBy(m => m.MemberName, StringComparer.Ordinal)
            .ToList();

        return new TypeDescriptor(target.FullyQualifiedName, target.SafeClassName, sortedMembers, diagnostics);
    }

    private static bool HasAnyHtbValidation(MemberDescriptor member)
        => member.Validation.NotNull
        || member.Validation.NotEmpty
        || member.Validation.MinLength > 0
        || member.Validation.MaxLength > 0
        || (member.Validation.HasRange && ParsedValidationRules.IsNumericType(member.BaseTypeName))
        || member.Validation.Pattern != null;

    private static void EmitHtbValidateRecordMethod(SourceBuilder builder, string fullyQualifiedName, IReadOnlyList<MemberDescriptor> readMembers)
    {
        builder.AppendLine($"public void ValidateRecord({fullyQualifiedName} instance)");
        builder.AppendLine("{");
        builder.Indent();
        foreach (var member in readMembers)
        {
            if (!member.HasGetter || !HasAnyHtbValidation(member))
                continue;

            builder.AppendLine($"if (_{member.MemberName}Index >= 0)");
            builder.AppendLine("{");
            builder.Indent();

            if (member.Validation.NotNull && (member.IsNullable || member.IsReferenceType))
            {
                if (member.IsNullable && !member.IsReferenceType)
                    builder.AppendLine($"if (!instance.{member.MemberName}.HasValue)");
                else
                    builder.AppendLine($"if (instance.{member.MemberName} == null)");

                builder.AppendLine("{");
                builder.Indent();
                builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, \"Property '{member.MemberName}' violated validation constraint: value cannot be null.\");");
                builder.Unindent();
                builder.AppendLine("}");
            }

            if (member.IsNullable && !member.IsReferenceType && member.Validation.HasRange && ParsedValidationRules.IsNumericType(member.BaseTypeName))
            {
                builder.AppendLine($"if (instance.{member.MemberName}.HasValue)");
                builder.AppendLine("{");
                builder.Indent();
                EmitHtbValidationChecks(builder, member);
                builder.Unindent();
                builder.AppendLine("}");
            }
            else
            {
                EmitHtbValidationChecks(builder, member);
            }

            builder.Unindent();
            builder.AppendLine("}");
        }
        builder.Unindent();
        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void EmitHtbValidationChecks(SourceBuilder builder, MemberDescriptor member)
    {
        // 1. NotNull validation (already handled for null reads in BindField/BindFieldAsync before calling this helper)

        // 2. NotEmpty validation
        if (member.Validation.NotEmpty)
        {
            builder.AppendLine($"if (instance.{member.MemberName} is string s && string.IsNullOrWhiteSpace(s))");
            builder.AppendLine("{");
            builder.Indent();
            builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, \"Property '{member.MemberName}' violated validation constraint: value cannot be empty.\");");
            builder.Unindent();
            builder.AppendLine("}");
        }

        // 3. MinLength validation
        if (member.Validation.MinLength > 0)
        {
            builder.AppendLine($"if (instance.{member.MemberName} is string sMin && sMin.Length < {member.Validation.MinLength})");
            builder.AppendLine("{");
            builder.Indent();
            builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, \"Property '{member.MemberName}' violated validation constraint: length must be at least {member.Validation.MinLength}.\");");
            builder.Unindent();
            builder.AppendLine("}");
        }

        // 4. MaxLength validation
        if (member.Validation.MaxLength > 0)
        {
            builder.AppendLine($"if (instance.{member.MemberName} is string sMax && sMax.Length > {member.Validation.MaxLength})");
            builder.AppendLine("{");
            builder.Indent();
            builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, \"Property '{member.MemberName}' violated validation constraint: length cannot exceed {member.Validation.MaxLength}.\");");
            builder.Unindent();
            builder.AppendLine("}");
        }

        // 5 & 6. Range validation
        if (member.Validation.HasRange && ParsedValidationRules.IsNumericType(member.BaseTypeName))
        {
            var valueExpr = member.IsNullable && !member.IsReferenceType
                ? $"instance.{member.MemberName}!.Value"
                : $"instance.{member.MemberName}";
            if (member.Validation.HasRangeMin)
            {
                string minCondition = member.Validation.FormatRangeMinViolationCondition(valueExpr, member.BaseTypeName);
                if (minCondition == "true")
                {
                    builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, global::System.FormattableString.Invariant($\"Property '{member.MemberName}' violated validation constraint: value {{{valueExpr}}} must be at least {member.Validation.FormatRangeMinInvariant()}.\"));");
                    return;
                }
                if (minCondition != "false")
                {
                    builder.AppendLine($"if ({minCondition})");
                    builder.AppendLine("{");
                    builder.Indent();
                    builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, global::System.FormattableString.Invariant($\"Property '{member.MemberName}' violated validation constraint: value {{{valueExpr}}} must be at least {member.Validation.FormatRangeMinInvariant()}.\"));");
                    builder.Unindent();
                    builder.AppendLine("}");
                }
            }
            if (member.Validation.HasRangeMax)
            {
                string maxCondition = member.Validation.FormatRangeMaxViolationCondition(valueExpr, member.BaseTypeName);
                if (maxCondition == "true")
                {
                    builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, global::System.FormattableString.Invariant($\"Property '{member.MemberName}' violated validation constraint: value {{{valueExpr}}} cannot exceed {member.Validation.FormatRangeMaxInvariant()}.\"));");
                    return;
                }
                if (maxCondition != "false")
                {
                    builder.AppendLine($"if ({maxCondition})");
                    builder.AppendLine("{");
                    builder.Indent();
                    builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, global::System.FormattableString.Invariant($\"Property '{member.MemberName}' violated validation constraint: value {{{valueExpr}}} cannot exceed {member.Validation.FormatRangeMaxInvariant()}.\"));");
                    builder.Unindent();
                    builder.AppendLine("}");
                }
            }
        }

        // 7. Pattern validation
        if (member.Validation.Pattern != null)
        {
            builder.AppendLine($"if (instance.{member.MemberName} is string sPat && !_pattern_{member.MemberName}.IsMatch(sPat))");
            builder.AppendLine("{");
            builder.Indent();
            builder.AppendLine($"throw new global::HeroParser.Htbs.HtbException(global::HeroParser.Htbs.HtbErrorCode.DeserializationError, \"Property '{member.MemberName}' violated validation constraint: value must match pattern '{new CSharpStringLiteral(member.Validation.Pattern).Escaped}'.\");");
            builder.Unindent();
            builder.AppendLine("}");
        }
    }

    private sealed record TypeDescriptor(
        string FullyQualifiedName,
        string SafeClassName,
        IReadOnlyList<MemberDescriptor> Members,
        IReadOnlyList<Diagnostic> Diagnostics);

    private sealed record MemberDescriptor(
        string MemberName,
        string HeaderName,
        int? AttributeIndex,
        string TypeName,
        string TypeOfTypeName,
        string BaseTypeName,
        bool IsNullable,
        bool IsReferenceType,
        bool HasSetter,
        bool HasGetter,
        ParsedValidationRules Validation);
}
